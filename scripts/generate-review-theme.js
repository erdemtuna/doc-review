import { REVIEW_PALETTE } from "../src/review-palette.js";

const root = fileURLToPath(new URL("../", import.meta.url));
const aliases = {
  canvas: "background", panel: "card", "card-border": "border",
  hair: "border", "hair-2": "border", dash: "border", "strong-border": "input",
  txt: "foreground", "strong-txt": "foreground", mute: "muted-foreground",
  "mute-2": "muted-foreground", faint: "muted-foreground", "faint-2": "muted-foreground",
  soft: "muted", chip: "secondary", "input-bg": "card", focus: "ring",
  danger: "destructive", "danger-soft": "review-removed", amber: "annotation-border",
  green: "review-added-foreground", "btn-bg": "primary", "btn-fg": "primary-foreground",
  "diff-paper": "card", "diff-ink": "foreground", "diff-muted": "muted-foreground",
  "diff-line": "border", "diff-removed": "review-removed", "diff-added": "review-added",
  "diff-delete": "review-delete", "diff-insert": "review-insert",
  "diff-delete-ink": "review-removed-foreground", "diff-insert-ink": "review-added-foreground",
  "diff-gap": "muted", "diff-accent": "review-modified-foreground",
};

export function validatePalette(palette) {
  if (!palette || Object.keys(palette).join(",") !== "light,dark") throw new Error("Palette must define light and dark themes");
  const roles = Object.keys(palette.light);
  if (!roles.length || roles.join(",") !== Object.keys(palette.dark).join(",")) throw new Error("Palette themes must define matching roles");
  for (const [theme, colors] of Object.entries(palette)) {
    for (const [role, color] of Object.entries(colors)) {
      if (!/^[a-z][a-z0-9-]*$/.test(role) || !/^#[0-9A-F]{6}([0-9A-F]{2})?$/.test(color)) {
        throw new Error(`Invalid palette entry: ${theme}.${role}`);
      }
    }
    for (const role of Object.values(aliases)) {
      if (!colors[role]) throw new Error(`Unresolved palette role: ${theme}.${role}`);
    }
  }
}

export function replaceRegion(source, name, content) {
  const start = `/* REVIEW_THEME_${name}_START */`;
  const end = `/* REVIEW_THEME_${name}_END */`;
  if (source.split(start).length !== 2 || source.split(end).length !== 2 || source.indexOf(end) < source.indexOf(start)) {
    throw new Error(`Missing, duplicate, or reversed review theme markers: ${name}`);
  }
  return source.slice(0, source.indexOf(start) + start.length) + "\n" + content + "\n" + source.slice(source.indexOf(end));
}

function declarations(colors, prefix = "") {
  return Object.entries(colors).map(([role, value]) => `  --${prefix}${role}: ${value};`).join("\n");
}

function documentColors(colors) {
  const mark = "mark[${MARK_ATTR}]";
  return `    ${mark} { background: ${colors["annotation-background"]}; color: ${colors["annotation-foreground"]}; text-decoration: underline ${colors["annotation-border"]}; }
    ${mark}:hover, ${mark}.eh-active { background: ${colors["annotation-active"]}; }
    ${mark}.eh-active { outline: 2px solid ${colors["annotation-border"]}; outline-offset: 1px; }
    ::selection { background: ${colors["annotation-active"]}; color: ${colors["annotation-foreground"]}; }`;
}

export function generateThemeSources(sdk, palette = REVIEW_PALETTE) {
  validatePalette(palette);
  const shell = `/* Generated by scripts/generate-review-theme.js. Do not edit colors here. */
${Object.entries(palette).map(([theme, colors]) => `${theme === "light" ? ":root,\n.review-ui" : ':root[data-theme="dark"],\n:root[data-theme="dark"].review-ui,\n:root[data-theme="dark"] .review-ui'} {
  color-scheme: ${theme};
${declarations(colors)}
}`).join("\n\n")}

:root, .review-ui {
${Object.entries(aliases).map(([alias, role]) => `  --${alias}: var(--${role});`).join("\n")}
  --focus-ring: 0 0 0 3px var(--ring);
  --review-shadow: 0 8px 24px var(--review-shadow-color), 0 1px 3px var(--review-shadow-color);
}
`;
  const shadow = Object.entries(palette).map(([theme, colors]) =>
    `    :host([data-review-theme="${theme}"]) {\n      color-scheme: ${theme};\n${declarations(colors, "review-").split("\n").map((line) => `    ${line}`).join("\n")}\n    }`).join("\n");
  const document = `const REVIEW_DOCUMENT_COLORS = {\n${Object.entries(palette).map(([theme, colors]) =>
    `  ${theme}: \`\n${documentColors(colors)}\n  \`,`).join("\n")}\n};`;
  sdk = replaceRegion(sdk, "SHADOW", shadow);
  sdk = replaceRegion(sdk, "DOCUMENT", document);
  for (const match of sdk.matchAll(/var\(--review-([a-z][a-z0-9-]*)\)/g)) {
    if (!(match[1] in palette.light)) throw new Error(`Unresolved SDK palette role: ${match[1]}`);
  }
  return { shell, sdk };
}

export async function generateReviewTheme({ check = false, directory = root } = {}) {
  const sdkFile = path.join(directory, "src", "sdk.js");
  const shellFile = path.join(directory, "src", "ui", "styles", "review-colors.css");
  const sdkSource = await readFile(sdkFile, "utf8");
  const output = generateThemeSources(sdkSource);
  for (const [file, content] of [[sdkFile, output.sdk], [shellFile, output.shell]]) {
    const previous = await readFile(file, "utf8").catch((error) => {
      if (error.code !== "ENOENT") throw error;
      return null;
    });
    if (previous === content) continue;
    if (check) throw new Error(`Stale generated review theme: ${path.relative(directory, file)}; run node scripts/generate-review-theme.js`);
    await writeFile(file, content);
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  const args = process.argv.slice(2);
  if (args.some((arg) => arg !== "--check")) throw new Error("Usage: node scripts/generate-review-theme.js [--check]");
  await generateReviewTheme({ check: args.includes("--check") });
}
